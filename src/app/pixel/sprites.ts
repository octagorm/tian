// written as rows of letters, one letter a pixel, coloured from the shared
// palette (a sprite may override a letter). Icons are 16 × 16; the quest's
// demons and heroes are 24 × 24. Light falls from the top left: a dark
// outline, shading toward the bottom right, a highlight or two.
//
// A sprite may have frames, which <Pix animate> plays: each frame the size
// of the first, `ms` a step, and `seq` the order of the steps as indices
// into [rows, ...frames] (a frame named twice is held twice as long).
// pixel/Pix.tsx draws them; /#gallery shows them all.

