export interface Sprite {
  rows: Array<string>
  pal?: Record<string, string>
  // Further frames, each as wide and high as rows
  frames?: Array<Array<string>>
  // Milliseconds a step lasts, and the frames in the order played
  ms?: number
  seq?: Array<number>
}

const s = (rows: Array<string>, pal?: Record<string, string>): Sprite => ({
  rows,
  pal,
})

// An animated sprite: its frames, the time a step lasts, and the order
function anim(
  all: Array<Array<string>>,
  ms: number,
  seq?: Array<number>,
  pal?: Record<string, string>,
): Sprite {
  return { rows: all[0], frames: all.slice(1), ms, seq, pal }
}

// A first frame and the frames after it, each given as the rows that differ
function frames(
  first: Array<string>,
  ...edits: Array<Record<number, string>>
): Array<Array<string>> {
  return [first, ...edits.map((e) => first.map((row, i) => e[i] ?? row))]
}

