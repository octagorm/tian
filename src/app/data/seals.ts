// Seals: achievements, each a red seal stamp (印章) with a character
// carved on it, earned across every game and kept in the bank
// (bank.seals). What earns each is in lib/achievements.ts; the seal
// itself is drawn by daily/Seal.tsx, and the album is games/seals.tsx.
//
// Each seal teaches its character: its pinyin, what it means, and a line
// about it.

export type SealGroup =
  'words' | 'days' | 'trip' | 'quest' | 'sound' | 'games' | 'garden' | 'album'

export interface SealDef {
  id: string
  // The characters carved on it: one, or two read top to bottom
  zh: string
  py: string
  means: string
  title: string
  // How it is earned
  how: string
  group: SealGroup
  // A square stamp unless said, round, or tall for two characters
  shape?: 'square' | 'round' | 'tall'
  // White characters cut into red (白文) or red characters standing on the
  // paper (朱文)
  style?: 'white' | 'red'
  note?: string
}

